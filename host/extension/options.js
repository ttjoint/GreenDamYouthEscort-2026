/**
 * Green Dam Youth Escort 2026 — options page.
 *
 * Reads and writes the same `config.json` the content script loads, so the
 * options page and the filter cannot disagree. It shows *counts* and switches,
 * never terms: a settings page that lists the terms is a copy of the list, and
 * this is a page a child can open.
 */
"use strict";

const DEFAULTS = {
  enabled: true,
  hideText: true,
  hideImages: true,
  serviceUrl: "http://127.0.0.1:17871",
};

/** Load the generated config; a missing file means "no lists", not an error. */
async function readConfig() {
  try {
    const response = await fetch(chrome.runtime.getURL("config.json"));
    return await response.json();
  } catch (error) {
    console.warn("[greendam] no config.json", error);
    return { terms: [], packs: [] };
  }
}

/**
 * Ask the local scoring service whether it is up, and whether it has a model.
 *
 * Three states, and the middle one is the reason this exists:
 *
 *   "未运行"           nothing is listening - images will not be checked
 *   "运行中，但未加载模型"  listening, but every reply is "not assessed"
 *   "运行中，模型：<name>"  images are actually being judged
 *
 * Collapsing the first two would tell a parent to check their model when the
 * service simply is not started, and the two need different fixes. A page that
 * silently claims image filtering is on while nothing listens is exactly the
 * failure the scoring service was written to end.
 */
async function probeService(serviceUrl) {
  const target = document.getElementById("service-status");
  if (!target) return;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 2000);
  try {
    const response = await fetch(`${serviceUrl.replace(/\/$/, "")}/health`, {
      signal: controller.signal,
      credentials: "omit",
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    if (payload && payload.assessing) {
      target.textContent = `运行中，模型：${payload.backend || "已加载"}`;
    } else {
      target.textContent = "运行中，但未加载模型 —— 图片不会被判定";
    }
  } catch (error) {
    target.textContent =
      "未运行 —— 图片不会被判定。请运行 python -m host.imaging";
  } finally {
    clearTimeout(timer);
  }
}

/** Render the pack summary. Counts only. */
function renderPacks(config) {
  const target = document.getElementById("packs");
  const packs = config.packs || [];
  if (packs.length === 0) {
    target.textContent = "未安装任何词库。";
    return;
  }
  const lines = packs.map((pack) => {
    const state = pack.usable ? "启用" : "停用";
    return `${pack.name}（${pack.id}）— ${state}，${pack.terms} 个词条`;
  });
  lines.push(`合计生效 ${config.terms ? config.terms.length : 0} 个词条。`);
  target.textContent = lines.join("\n");
  target.style.whiteSpace = "pre-line";
}

async function main() {
  const config = await readConfig();
  const stored = await chrome.storage.local.get(DEFAULTS);

  const enabled = document.getElementById("enabled");
  const hideText = document.getElementById("hideText");
  const hideImages = document.getElementById("hideImages");
  const serviceUrl = document.getElementById("serviceUrl");
  const status = document.getElementById("status");
  const emptyWarning = document.getElementById("empty-warning");

  enabled.checked = stored.enabled;
  hideText.checked = config.hideText !== false;
  hideImages.checked = config.hideImages !== false;
  serviceUrl.value = stored.serviceUrl;

  const termCount = config.terms ? config.terms.length : 0;
  status.textContent = enabled.checked
    ? `已启用，${termCount} 个词条生效`
    : "已停用";
  emptyWarning.hidden = termCount > 0;

  enabled.addEventListener("change", async () => {
    await chrome.storage.local.set({ enabled: enabled.checked });
    status.textContent = enabled.checked
      ? `已启用，${termCount} 个词条生效`
      : "已停用";
    // Tell every open tab, so the change does not need a reload.
    const tabs = await chrome.tabs.query({});
    for (const tab of tabs) {
      if (!tab.id) continue;
      chrome.tabs
        .sendMessage(tab.id, { type: "set-enabled", enabled: enabled.checked })
        .catch(() => {
          // Tabs without the content script (chrome:// pages, the store) reject;
          // that is expected and not worth reporting.
        });
    }
  });

  serviceUrl.addEventListener("change", async () => {
    await chrome.storage.local.set({ serviceUrl: serviceUrl.value.trim() });
    probeService(serviceUrl.value.trim());
  });

  // The two scope switches live in config.json, which is generated by the host.
  // Changing them here would be overwritten on the next regeneration, so they
  // are shown read-only with a pointer to the command that owns them.
  hideText.disabled = true;
  hideImages.disabled = true;

  renderPacks(config);
  probeService(stored.serviceUrl || DEFAULTS.serviceUrl);
}

main();
