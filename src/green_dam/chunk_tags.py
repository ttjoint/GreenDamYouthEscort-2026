"""语义块标记符（Semantic-Chunk Tag）。

## 理论出处

张艳红《HNC 理论的辅语义块以及语义块标记符》(CCL-99-003,
中科院声学所)。该文对俞士汶《现代汉语语法信息词典详解》"介词表"
的 85 个介词筛选 76 个、外加 4 个，总计 **80 个**，按语义块标记
功能人工分类（基于 8,872 个标注了介词结构的句子）：

- 主语义块标记符 32 个
- 辅语义块标记符 56 个
- 两可语义块标记符 9 个

（三类有交叉：13 个兼主/辅，4 个兼主/两可，2 个兼辅/两可，
2 个三者皆可。）

工程意义（原文结论）：纯类标记符合计占 81%——程序判定语义块
类型时，**可以直接从介词得到依据**，不必动用句类知识。这一层
不依赖绿坝缺失的 `SENTEN.LIB`，是 HNC 句类分析链路里唯一一份
完备、可枚举、可直接落地的数据。

## 论文统计口径的一处冲突（必须先说清）

论文正文说"总计 80 个，主 32 / 辅 56 / 两可 9"，但把三张表的
逐项清单（p.18/19 原图）加总，唯一介词数是 **78**：

    纯主 17 + 主辅兼 11 + 主两可兼 2 + 纯辅 43 + 纯两可 5 = 78
    （"为（去声）/从"三者皆可，各角色行各计 1 次）

用行内列出次数计则是：主 17+11+2+2=32、辅 43+11+2=56，恰好
等于论文的 32/56。所以 80/32/56 是**行次（incidence）**，78 是
**唯一数**。本表按唯一数落地，角色用 Flag 叠加表示，两个口径
都能从表里重建；tests/test_chunk_tags.py 以两组数分别为锚。

## 复刻边界（诚实边界）

- 表内数据逐项对照论文扫描件核对（第 4–5 页原图）。
- 论文个别排印含混处（如"至于 为（去声）"）按原文保留，
  不做增删。`为（阳平）/为（去声）` 视为不同标记符。
- 这张表解决"介词标记哪个语义块"，**不**给出句类码——句类
  判定仍是 `hnc.py` 的职责。本模块是句类感知的**前置过滤器**。
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Flag, auto

__all__ = [
    "TagRole",
    "ChunkTag",
    "TAG_TABLE",
    "tag_of",
    "roles_of",
    "maximal_tag_at",
]


class TagRole(Flag):
    """标记符的语义块角色（可叠加，对应论文的兼类）。"""

    NONE = 0
    MAIN = auto()      # 主语义块标记符
    SECONDARY = auto()  # 辅语义块标记符
    DUAL = auto()       # 两可语义块标记符（主辅不分）


# ---------------------------------------------------------------------------
# 论文原表。排序保持论文行文顺序，便于逐项核对。
# ---------------------------------------------------------------------------

_PURE_MAIN = (
    "把", "被", "为（阳平）", "对", "对于", "连", "往",
    "跟", "同", "和", "与", "就", "让", "叫", "替", "管", "将",
)

_MAIN_SEC = (  # 兼主辅
    "打", "由", "向（着）", "朝（着）", "以", "于", "为（去声）",
    "通过", "从", "经过", "经",
)

_MAIN_DUAL = (  # 兼主两可（不含三者皆可的为/从）
    "给", "至于",
)

_PURE_SECONDARY = (
    "按", "按照", "本着", "根据", "基于", "鉴于",
    "据", "像……一样", "离", "拿", "依", "依据",
    "依照", "照", "照着", "遵照", "趁", "趁着", "当",
    "当着", "及至", "借", "临", "每当", "凭", "凭借",
    "顺着", "随着", "为了", "为着", "沿", "沿着",
    "因", "因为", "用", "由于", "在", "正如……那样", "只限",
    "至", "待", "自", "自从",
)

# （无独立"兼辅两可"组：那 2 个就是三者皆可的"为（去声）/从"。）

_PURE_DUAL = (
    "作为", "关于", "针对", "就……而言", "拿……来说",
)

# 注：论文正文说"兼辅两可的有 2 个"，指的正是"为（去声）/从"
# 这两个三者皆可的介词（它们同时出现在辅表的"兼两可"行里）。
# 用论文发布的五个总数（80/32/56/9/纯类 17+43+5）联立验证，
# 唯一自洽的分组是：主辅兼 11、主两可兼 2、三者皆可 2、辅两可兼 0。
# tests/test_chunk_tags.py 以这五个数为锚点。

# 兼主两可 / 兼辅两可 / 兼三者已在上面三张兼类表中列出，不重复。


@dataclass(frozen=True)
class ChunkTag:
    """一个介词标记符及其全部角色。"""

    surface: str          # 论文原表写法（含"（阳平）"等注记）
    roles: TagRole
    # 搭配型标记符（如"拿……来说"）的块尾部分；None = 纯块首。
    tail: str | None = None
    # "为（阳平）/为（去声）"的读音注记；无注记为 None。
    reading: str | None = None


def _mk(surface: str, roles: TagRole, tail: str | None = None,
        reading: str | None = None) -> tuple[str, ChunkTag]:
    return surface, ChunkTag(surface, roles, tail, reading)


TAG_TABLE: dict[str, ChunkTag] = dict([
    # ---- 纯主 -------------------------------------------------------
    *(_mk(s, TagRole.MAIN) for s in _PURE_MAIN),
    # ---- 兼主辅 -----------------------------------------------------
    *(_mk(s, TagRole.MAIN | TagRole.SECONDARY) for s in _MAIN_SEC),
    # ---- 兼主两可 ---------------------------------------------------
    *(_mk(s, TagRole.MAIN | TagRole.DUAL) for s in _MAIN_DUAL),
    # ---- 纯辅 -------------------------------------------------------
    *(_mk(s, TagRole.SECONDARY) for s in _PURE_SECONDARY),
    # ---- 兼辅两可：无。论文辅表"兼两可"行列的"为（去声）、从"
    # 即三张表交叉得到的 2 个三者皆可标记符，见下一条，不重复。
    # ---- 纯两可 -----------------------------------------------------
    *(_mk(s, TagRole.DUAL) for s in _PURE_DUAL),
    # ---- 三者皆可 ---------------------------------------------------
    # 论文：三种标记符均可作的有 2 个。对照三表行文，"为（去声）"
    # 与"从"在主/辅/两可三张兼类行里均出现，即为这 2 个。
    *(
        _mk(s, TagRole.MAIN | TagRole.SECONDARY | TagRole.DUAL, reading=r)
        for s, r in [("为（去声）", "去声"), ("从", None)]
    ),
])

# 搭配型标记符的块尾（论文："以……为……"的"为"是尾标，
# "……来说"是真尾；"拿……来说"、"就……而言"同理）。
TAILS: dict[str, str] = {
    "拿……来说": "来说",
    "就……而言": "而言",
    "像……一样": "一样",
    "正如……那样": "那样",
}


def _lookup_key(word: str) -> str | None:
    """把文本里的介词映射到表键。

    处理两类差异：
    - "向着/朝着" 是 "向（着）/朝（着）" 的带"着"形式；
    - "为" 依赖读音，文本里无法判断，保守起见返回两个键，
      由调用方结合上下文取舍（默认取"为（去声）"，因兼类最多，
      留给后续句类判定消歧）。
    """
    if word in TAG_TABLE:
        return word
    if word in ("向着", "朝着"):
        return word[0] + "（着）"
    if word == "为":
        return "为（去声）"
    return None


def tag_of(word: str) -> ChunkTag | None:
    """查一个词的标记符记录。非标记符返回 None。"""
    key = _lookup_key(word)
    return TAG_TABLE[key] if key else None


def roles_of(word: str) -> TagRole:
    """一个词的语义块角色集合。非标记符返回 TagRole.NONE。"""
    t = tag_of(word)
    return t.roles if t else TagRole.NONE


def maximal_tag_at(text: str, i: int) -> tuple[ChunkTag, int] | None:
    """在 text[i:] 处做最长匹配，返回 (标记符, 消耗长度)。

    先试 4/3/2 字窗口（覆盖"正如……那样"前半、"按照"等多字
    标记符），再退到单字。命中"像/正如/拿/就"等搭配型首部时，
    调用方需继续找块尾。
    """
    for n in (4, 3, 2):
        chunk = text[i : i + n]
        if len(chunk) < n:
            break
        tag = tag_of(chunk)
        if tag:
            return tag, n
    ch = text[i : i + 1]
    tag = tag_of(ch)
    if tag:
        return tag, 1
    return None
